const grupoPorId = new Map(GRUPOS.map((g) => [g.id, g]))

/** "aula-06 p28-30" → { arquivo: "aula-06…", paginas: "28-30" } (prefixo basta) */
function fontes(...refs: string[]): Fonte[] {
  return refs.map((r) => {
    const [arquivo, pag] = r.split(' ')
    return { arquivo, paginas: pag?.replace(/^p/, '') }
  })
}

type Extra = Partial<Pick<Topico, 'semSlide' | 'naoVisto'>>

function t(
  grupo: string,
  id: string,
  titulo: string,
  nivel: Nivel,
  resumo: string,
  refs: string[] = [],
  extra: Extra = {},
): Topico {
  const g = grupoPorId.get(grupo)
  if (!g) throw new Error(`grupo desconhecido: ${grupo}`)
  return { id, titulo, unidade: g.unidade, grupo, nivel, etapa: g.etapa, resumo, fontes: fontes(...refs), ...extra }
}

